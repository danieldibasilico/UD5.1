package clases;
public class DiaAdviento {

    private boolean estado;
    private int NumDia;
    private String sorpresa;

    public DiaAdviento(int numDia) {
        this.estado = estado;
        this.NumDia = numDia;
        this.sorpresa = sorpresa;
    }
    public boolean isEstado() {
        return estado;
    }
    public void setEstado(boolean estado) {
        this.estado = estado;
    }
    public int getNumDia() {
        return NumDia;
    }
    public void setNumDia(int numDia) {
        NumDia = numDia;
    }
    public String getSorpresa() {
        return sorpresa;
    }
    public void setSorpresa(String sorpresa) {
        this.sorpresa = sorpresa;
    }
}